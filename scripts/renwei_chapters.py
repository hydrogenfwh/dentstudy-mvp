def score(text: str, keywords: str) -> float:
    return sum(
        (min(len(word), 7) ** 2) * min(len(re.findall(re.escape(word), text, flags=re.I)), 2)
        for word in keywords.split("|")
    )


def classify(question: dict) -> tuple[str, str]:
    text = question.get("sharedStem", "") + "\n" + question["stem"]
    options = "\n".join(question["options"].values())
    subject = question["subject"]
    if subject == "口腔内科学":
        candidates = [
            (score(text, words) + .06 * score(options, words), target)
            for target, words in INTERNAL_SUBJECTS
        ]
        best, target = max(candidates)
        if best > 0:
            subject = target
    rules = RULES.get(subject, [])
    candidates = [
        (score(text, words) + .06 * score(options, words), -i, title)
        for i, (title, words) in enumerate(rules)
    ]
    if not candidates or max(candidates)[0] < 4:
        return subject, "综合练习"
    return subject, max(candidates)[2]


